# Writes tools/video-shotlist-math.js: every G4 Math teacher-video slot, with its repo path,
# whether the .mp4 already exists, the script, and the on-screen visuals (cards + photos) for each slot.
# Open the studio with ?subject=math to use it. Rerun after adding a lesson's video plan
# (optima-4th-science/data/videos/lesson-WW-DD.json) or recording videos.
import json, os, re, glob, html, base64, io, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ELA = os.path.dirname(HERE)
SCI = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(ELA), 'optima-4th-math')
try:
    from PIL import Image
except ImportError:
    Image = None
def t_(h): return html.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', h))).strip()
def pic(path):
    f = os.path.join(SCI, path)
    if not os.path.exists(f): return ''
    if Image is None:
        return 'data:image/%s;base64,' % ('png' if f.endswith('.png') else 'jpeg') + base64.b64encode(open(f, 'rb').read()).decode()
    im = Image.open(f).convert('RGB'); im.thumbnail((900, 900)); b = io.BytesIO(); im.save(b, 'JPEG', quality=84)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
man = {}
if os.path.exists(os.path.join(SCI, 'video-manifest.json')):
    man = json.load(open(os.path.join(SCI, 'video-manifest.json'), encoding='utf-8'))
lessons, pics, caps, docs = [], {}, {}, {}
def tidy(t):
    # each [ON SCREEN: …] cue must be its own paragraph for the studio to turn it into buttons
    return re.sub(r'(\[\s*ON SCREEN\s*:[^\]]*\])[ \t]*\n(?!\n)', r'\1\n\n', t or '').strip()
for vf in sorted(glob.glob(os.path.join(SCI, 'data', 'videos', 'lesson-*.json'))):
    V = json.load(open(vf, encoding='utf-8'))
    w, d = V['lesson'].split('.')
    lf = next(iter(sorted(glob.glob(os.path.join(SCI, 'math-lesson-4-%02d-%s-*.html' % (int(w), d))), key=len)), '')
    src = open(lf, encoding='utf-8', errors='ignore').read() if lf else ''
    tm = re.search(r'<title>([^<]*)', src)
    title = V.get('title') or (html.unescape(tm[1]) if tm else 'Lesson ' + V['lesson'])
    words = []
    for fm in re.finditer(r'class="flip-card-front">(.*?)class="fc-def">(.*?)</div>', src, re.S):
        em = re.search(r'class="fc-emoji">(.*?)</div>', fm[1], re.S); wd = re.search(r'class="fc-word">(.*?)</div>', fm[1], re.S)
        if wd: words.append({'w': t_(wd[1]), 'd': t_(fm[2]), 'e': t_(em[1]) if em else ''})
    pre = V['prefix']; mk = V.get('manifestKey', '')
    def done(slot):
        p = os.path.join(SCI, 'assets', 'video', 'teacher', '%s-%s.mp4' % (pre, slot))
        e = man.get('%s-%s' % (mk, slot)) or {}
        return os.path.exists(p) or e.get('status') == 'ready'
    clips, parts, doc = [], {}, ['# Lesson %s teacher videos' % V['lesson'], '']
    for slot, S in V['slots'].items():
        redo = slot in (V.get('redo') or [])  # an old take that no longer matches the lesson: record it again
        clips.append({'id': slot, 'label': ('🔁 Re-record · ' if redo else '') + ('🖥 Screen · ' if S.get('screen') else 'Teacher · ') + S['label'] + ' (' + S.get('length', '') + ')' + (' · ' + S['where'] if S.get('where') else ''), 'path': 'teacher/%s-%s' % (pre, slot),
                      'done': False if redo else done(slot), 'redo': redo, 'script': tidy(S.get('script', '')), 'want': bool(S.get('want')) or redo})
        parts[slot] = S.get('parts', [])
        doc += ['## %s · %s-%s' % (S['label'], pre, slot), '', tidy(S.get('script', '')), '']
    for o in V.get('other', []):
        slot = o['id'] if isinstance(o, dict) else o
        lab = (o.get('label') or slot) + (' (' + o['length'] + ')' if isinstance(o, dict) and o.get('length') else '') if isinstance(o, dict) else slot
        clips.append({'id': slot, 'label': 'Teacher · ' + lab + ' · optional, no script yet', 'path': 'teacher/%s-%s' % (pre, slot), 'done': done(slot), 'script': ''})
    for k, P in V.get('pics', {}).items():
        if k not in pics:
            u = pic(P['src'])
            if u: pics[k] = u; caps[k] = P.get('cap', '')
    key = '%s-%s' % (int(w), d)
    docs[key] = '\n'.join(doc)
    lessons.append({'w': int(w), 'd': d, 'title': 'Lesson %s: %s' % (V['lesson'], title), 'file': os.path.basename(lf),
                    'fileUrl': '../../optima-4th-math/' + os.path.basename(lf) if lf else '',
                    'clips': clips, 'cards': {'sci': parts}, 'words': words})
lessons.sort(key=lambda L: (L['w'], L['d']))
out = json.dumps({'lessons': lessons, 'poems': [], 'teacher': [], 'teacherDocs': docs, 'pics': pics, 'picCaps': caps}, ensure_ascii=False, separators=(',', ':'))
open(os.path.join(HERE, 'video-shotlist-math.js'), 'w', encoding='utf-8').write(
    '/* generated by tools/video_shotlist_math.py from optima-4th-math/data/videos: rerun after adding a lesson */\nwindow.SHOTLIST=' + out + ';\n')
print(len(lessons), 'lessons,', sum(len(L['clips']) for L in lessons), 'slots,', len(pics), 'pictures,', len(out) // 1024, 'KB')
